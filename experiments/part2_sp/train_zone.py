"""
Part II / Lever A1 — train Nazari on a single SP zone (direct real-point sampling).

Method A: train per zone, matching the eval setup exactly —
  - customers sampled (without replacement) from the zone's real TRAIN pool
  - depot fixed at the zone's normalized centroid (same as the eval instances)

No KDE: with thousands of real customers per zone, instances are built by
sampling real coordinates directly (train and test pools are disjoint, so there
is no leakage). This isolates the DATA lever (A1). Density feature (A2) and POMO
(A3) come in later scripts. Baseline here is Kool, same as Part I, so the only
change vs the Part I zero-shot is train == eval distribution.

Requires:
    artifacts/instances/olist_sp_c{ID}_train_pool.pt
        — generated by: uv run eda/05_split_train_test.py

Run (Kaggle T4 or local):
    uv run experiments/part2_sp/train_zone.py
"""

import os
import torch
from pathlib import Path

import sys
sys.path.insert(0, str(Path(__file__).parent.parent.parent))
from src.trainer import Trainer

# ------------------------------------------------------------------
# Config
# ------------------------------------------------------------------
CLUSTER_ID       = 5          # C5 / Centro-Sul
N_CUSTOMERS      = 20
VEHICLE_CAPACITY = 30
BATCH_SIZE       = 512
N_EPOCHS         = 20_000
SAVE_EVERY       = 2_000
LR               = 1e-4
MAX_GRAD_NORM    = 2.0
BASELINE         = "kool"

# Experiment ID: {size}_{dist}_{zone}__{baseline}__{features}
RUN_NAME       = f"vrp{N_CUSTOMERS}_real_c{CLUSTER_ID}__{BASELINE}__base"
CHECKPOINT_DIR = f"artifacts/checkpoints/{RUN_NAME}"
WANDB_PROJECT  = f"nazari-vrp{N_CUSTOMERS}-real-c{CLUSTER_ID}"

device = "cuda" if torch.cuda.is_available() else "cpu"
print(f"Device: {device}\n")

# ------------------------------------------------------------------
# Load the zone train pool (real coords + fixed centroid depot)
# ------------------------------------------------------------------
pool_path = Path(f"artifacts/instances/olist_sp_c{CLUSTER_ID}_train_pool.pt")
if not pool_path.exists():
    raise FileNotFoundError(
        f"{pool_path} not found. Run: uv run eda/05_split_train_test.py"
    )
data  = torch.load(pool_path, map_location="cpu", weights_only=False)
pool  = data["coords"].numpy()          # (n_train, 2)
depot = data["depot"].numpy()           # (2,)

print(f"Run        : {RUN_NAME}")
print(f"Train pool : {len(pool):,} real customers (zone C{CLUSTER_ID})")
print(f"Depot      : ({depot[0]:.3f}, {depot[1]:.3f})  [fixed zone centroid]")
print(f"VRP{N_CUSTOMERS} | cap={VEHICLE_CAPACITY} | batch={BATCH_SIZE} | "
      f"baseline={BASELINE} | epochs={N_EPOCHS}\n")

# ------------------------------------------------------------------
# Train
# ------------------------------------------------------------------
trainer = Trainer(
    n_customers=N_CUSTOMERS,
    vehicle_capacity=VEHICLE_CAPACITY,
    batch_size=BATCH_SIZE,
    embed_dim=128,
    lr=LR,
    max_grad_norm=MAX_GRAD_NORM,
    device=device,
    use_wandb=True,
    distribution="pool",
    pool=pool,
    depot=depot,
    baseline=BASELINE,
    run_name=RUN_NAME,
    wandb_project=WANDB_PROJECT,
)

print(f"Actor params: {sum(p.numel() for p in trainer.actor.parameters()):,}\n")

os.makedirs(CHECKPOINT_DIR, exist_ok=True)
trainer.train(
    n_epochs=N_EPOCHS,
    save_every=SAVE_EVERY,
    checkpoint_dir=CHECKPOINT_DIR,
)
print(f"Done. Checkpoints saved to {CHECKPOINT_DIR}\n")
