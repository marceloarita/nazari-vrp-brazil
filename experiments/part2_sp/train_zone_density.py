"""
Part II / Hypothesis 2 — per-zone training + KDE density feature.

Preserves Hypothesis 1 exactly (per-zone training, direct real-point sampling
from the train pool, fixed centroid depot, leakage-free split) and adds one
thing: a standardized KDE density `log p(x, y)` as a third node feature, so the
model knows whether a stop sits in a dense or sparse part of the zone.

The only change vs H1 is the input: nodes are `[x, y, density]` instead of `[x, y]`.
Baseline stays Kool, so any difference is attributable to the density feature.

Requires:
    artifacts/instances/olist_sp_c{ID}_train_pool.pt with `coords_dens` / `depot_dens`
        — generated by: uv run eda/05_split_train_test.py && uv run eda/06_add_density.py

Run (Kaggle T4 or local):
    uv run experiments/part2_sp/train_zone_density.py
"""

import os
import torch
from pathlib import Path

import sys
sys.path.insert(0, str(Path(__file__).parent.parent.parent))
from src.trainer import Trainer

# ------------------------------------------------------------------
# Config
# ------------------------------------------------------------------
CLUSTER_ID       = 5          # C5 / Centro-Sul
N_CUSTOMERS      = 20
VEHICLE_CAPACITY = 30
BATCH_SIZE       = 512
N_EPOCHS         = 20_000
SAVE_EVERY       = 2_000
LR               = 1e-4
MAX_GRAD_NORM    = 2.0
BASELINE         = "kool"

# Experiment ID: {size}_{dist}_{zone}_{baseline}_{features}
RUN_NAME       = f"vrp{N_CUSTOMERS}_real_c{CLUSTER_ID}_{BASELINE}_dens"
CHECKPOINT_DIR = f"artifacts/checkpoints/{RUN_NAME}"
# Same W&B project as H1 (nazari-vrp20-real-c5) so H1 and H2 curves compare side by side.
WANDB_PROJECT  = f"nazari-vrp{N_CUSTOMERS}-real-c{CLUSTER_ID}"

device = "cuda" if torch.cuda.is_available() else "cpu"
print(f"Device: {device}\n")

# ------------------------------------------------------------------
# Load the zone train pool WITH the density feature
# ------------------------------------------------------------------
pool_path = Path(f"artifacts/instances/olist_sp_c{CLUSTER_ID}_train_pool.pt")
if not pool_path.exists():
    raise FileNotFoundError(f"{pool_path} not found. Run eda/05_split_train_test.py first.")
data = torch.load(pool_path, map_location="cpu", weights_only=False)
if "coords_dens" not in data:
    raise KeyError(
        f"{pool_path} has no density feature. Run: uv run eda/06_add_density.py"
    )

pool  = data["coords_dens"].numpy()   # (n_train, 3) = [x, y, density]
depot = data["depot_dens"].numpy()    # (3,)

print(f"Run        : {RUN_NAME}")
print(f"Train pool : {len(pool):,} real customers (zone C{CLUSTER_ID}), features = [x, y, density]")
print(f"Depot      : ({depot[0]:.3f}, {depot[1]:.3f})  density={depot[2]:+.2f}")
print(f"VRP{N_CUSTOMERS} | cap={VEHICLE_CAPACITY} | batch={BATCH_SIZE} | "
      f"baseline={BASELINE} | epochs={N_EPOCHS}\n")

# ------------------------------------------------------------------
# Train (static_dim=3 is inferred from the pool width)
# ------------------------------------------------------------------
trainer = Trainer(
    n_customers=N_CUSTOMERS,
    vehicle_capacity=VEHICLE_CAPACITY,
    batch_size=BATCH_SIZE,
    embed_dim=128,
    lr=LR,
    max_grad_norm=MAX_GRAD_NORM,
    device=device,
    use_wandb=True,
    distribution="pool",
    pool=pool,
    depot=depot,
    baseline=BASELINE,
    run_name=RUN_NAME,
    wandb_project=WANDB_PROJECT,
)

print(f"Actor params: {sum(p.numel() for p in trainer.actor.parameters()):,}\n")

os.makedirs(CHECKPOINT_DIR, exist_ok=True)
trainer.train(
    n_epochs=N_EPOCHS,
    save_every=SAVE_EVERY,
    checkpoint_dir=CHECKPOINT_DIR,
)
print(f"Done. Checkpoints saved to {CHECKPOINT_DIR}\n")
